# Python Loops

# For loop
print("Numbers from 1 to 5:")

for number in range(1, 6):
    print(number)

# Loop through a list
fruits = ["Apple", "Banana", "Mango"]

print("\nMy fruits:")

for fruit in fruits:
    print(fruit)

# While loop
print("\nCountdown:")

count = 5

while count > 0:
    print(count)
    count -= 1

print("Done!")
